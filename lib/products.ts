function generateFinalProducts(): Product[] {
  return realProducts.map((p) => ({
    ...p,
    priceIdr: Math.round(p.priceUsd * EXCHANGE_RATE),
    volumetricWeightG: Math.max(p.weightG, Math.round((p.lengthCm * p.widthCm * p.heightCm) / 5)),
  }));
}

export const allProducts: Product[] = generateFinalProducts();

export function getProductsBySku(sku: string): Product | undefined {
  return allProducts.find((p) => p.sku === sku);
}

export function getProductsByCategory(category: string): Product[] {
  if (category === "All" || !category) return allProducts;
  return allProducts.filter((p) => p.category === category);
}

export function searchProducts(query: string): Product[] {
  const q = query.toLowerCase().trim();
  if (!q) return allProducts;

  const tokens = q.split(/\s+/);
  return allProducts.filter((p) => {
    const searchable = `${p.title} ${p.brand} ${p.category} ${p.description} ${p.sku}`.toLowerCase();
    return tokens.every((token) => searchable.includes(token));
  });
}

